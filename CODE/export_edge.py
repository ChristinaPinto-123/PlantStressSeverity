"""Export the trained edge model (smooth -> SNV -> band select -> standardise -> LDA) to an
int8-quantised C header for the ESP32.

Features are standardised on-device in float ((f - MEAN) * INV_STD), then the LDA weights
(int8, one scale per class) are applied; bias and softmax stay in float.
(Folding standardisation into the weights was tried and rejected: raw temp/hum values make the
folded weights very sensitive to int8 rounding.)

On-device feature vector order:  [selected SNV bands..., temp, hum]
"""
import numpy as np


def extract_linear(edge_model):
    ct = edge_model.named_steps["pre"]
    sel = ct.named_transformers_["spec"].named_steps["select"].get_support(indices=True)
    scaler, lda = edge_model.named_steps["scale"], edge_model.named_steps["clf"]
    return sel, lda.coef_, lda.intercept_, scaler.mean_, 1.0 / scaler.scale_


def quantize_int8(W):
    scale = np.abs(W).max(axis=1) / 127.0
    scale[scale == 0] = 1.0
    Wq = np.clip(np.round(W / scale[:, None]), -127, 127).astype(np.int8)
    return Wq, scale


def predict_int8(X, n_bands, sel, Wq, scale, b, mean, inv_std):
    """Bit-faithful Python mirror of the firmware math (used to verify the export)."""
    from preprocess import moving_average, snv
    S = snv(moving_average(X[:, :n_bands]))
    F = np.hstack([S[:, sel], X[:, n_bands:]])
    F = (F - mean) * inv_std
    logits = (F @ Wq.T.astype(float)) * scale + b
    logits -= logits.max(axis=1, keepdims=True)
    p = np.exp(logits)
    return p / p.sum(axis=1, keepdims=True)


def export_header(edge_model, n_bands, wl, path="edge_model.h", conf_threshold=0.80):
    sel, W, b, mean, inv_std = extract_linear(edge_model)
    Wq, scale = quantize_int8(W)
    n_cls, n_feat = Wq.shape
    n_clim = n_feat - len(sel)
    fmt = lambda a, f: ", ".join(f.format(v) for v in a)
    lines = [
        "// Auto-generated by export_edge.py - do not edit",
        "#pragma once", "#include <stdint.h>",
        f"#define N_CH {n_bands}", f"#define N_SEL {len(sel)}", f"#define N_CLIM {n_clim}",
        f"#define N_FEAT {n_feat}", f"#define N_CLASSES {n_cls}",
        f"#define CONF_THRESHOLD {conf_threshold}f",
        f"static const float CH_WL[N_CH] = {{{fmt(wl, '{:.0f}')}}};",
        f"static const uint8_t SEL_IDX[N_SEL] = {{{fmt(sel, '{}')}}};",
        f"static const float W_SCALE[N_CLASSES] = {{{fmt(scale, '{:.8e}')}}};",
        f"static const float BIAS[N_CLASSES] = {{{fmt(b, '{:.8e}')}}};",
        f"static const float F_MEAN[N_FEAT] = {{{fmt(mean, '{:.8e}')}}};",
        f"static const float F_INV_STD[N_FEAT] = {{{fmt(inv_std, '{:.8e}')}}};",
        "static const int8_t W_Q[N_CLASSES][N_FEAT] = {",
    ]
    lines += ["  {" + fmt(row, "{}") + "}," for row in Wq]
    lines += ["};", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    flash_bytes = Wq.size + 4 * (len(scale) + len(b) + len(wl) + 2 * n_feat) + len(sel)
    return {"selected_bands_nm": [float(wl[i]) for i in sel], "flash_bytes": int(flash_bytes), "path": path}
